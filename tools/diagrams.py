def gate_flow():
    """Vertical, not horizontal.

    The first cut was a 890px-wide left-to-right flow, which is fine on the
    landing page and wrong here: the docs column is about 700px, so it scrolled
    on every screen. A diagram the reader has to drag is a diagram they skip."""
    b = ['<g>',
         '<defs><marker id="rm-arrow2" viewBox="0 0 8 8" refX="6.5" refY="4" markerWidth="5" '
         'markerHeight="5" orient="auto"><path d="M0.5 1 L6.5 4 L0.5 7 Z" class="e-head"/></marker></defs>']
    b.append(_box(70, 14, 250, 42, "graph on main", "stage", sub="the base"))
    b.append(_box(380, 14, 250, 42, "graph on the branch", "stage", sub="the head"))
    b.append('<path d="M195 58 C195 78, 350 70, 350 92" class="e-line e-arrow" marker-end="url(#rm-arrow2)"/>')
    b.append('<path d="M505 58 C505 78, 350 70, 350 92" class="e-line e-arrow" marker-end="url(#rm-arrow2)"/>')
    b.append(_box(225, 96, 250, 42, "diff", "stage", sub="matched on (from, to, relation)"))
    b.append('<path d="M350 140 V174" class="e-line e-arrow" marker-end="url(#rm-arrow2)"/>')
    b.append(_box(225, 178, 250, 42, "gates", "stage", sub="added edges only"))
    outs = [("comment on the PR", 10, "ok"), ("SARIF to security tab", 245, "ok"),
            ("exit 3 — build fails", 480, "down")]
    for name, x, cls in outs:
        b.append(f'<path d="M350 222 C350 244, {x + 105} 236, {x + 105} 258" '
                 f'class="e-line e-arrow" marker-end="url(#rm-arrow2)"/>')
        b.append(_box(x, 262, 210, 34, name, cls))
    b.append('</g>')
    return figure(
        _svg(700, 306,
             "How the pull-request gate runs",
             "The graph on main and the graph on the branch feed a diff, matched on from, to "
             "and relation. Gates evaluate added edges only, producing three outcomes: a "
             "comment on the pull request, SARIF for the security tab, and exit code 3 when "
             "a gate trips.",
             "".join(b)),
        min_width=640)


