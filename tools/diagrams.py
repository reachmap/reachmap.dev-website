def confidence_scale():
    """Three chips, not three bars.

    The first cut drew bars of decreasing length. That is a quantity, and the
    paragraph above the diagram says in as many words that confidence is a
    bucket and not a number — the picture was arguing with the text. Equal
    chips say "three named categories", which is the actual claim."""
    rows = [
        ("confirmed", "conf", "The manifest names the target outright",
         "a literal ARN, an ExternalName, a proxy argument, a StorageClass provisioner"),
        ("likely", "likely", "Parsed from config and matched to a catalog rule",
         "a hostname the catalog recognises, or a shared-credential join"),
        ("possible", "poss", "Something is there, but nothing names it",
         "an endpoint no rule recognises, or a target inside a Secret"),
    ]
    b = ['<g>']
    for i, (name, cls, claim, eg) in enumerate(rows):
        y = 6 + i * 62
        b.append(f'<rect x="0" y="{y + 6}" width="12" height="12" rx="3" class="cf-chip cf-{cls}"/>')
        b.append(f'<text x="24" y="{y + 17}" class="cf-name cf-{cls}">{name}</text>')
        b.append(f'<text x="150" y="{y + 17}" class="cf-claim">{html.escape(claim)}</text>')
        b.append(f'<text x="150" y="{y + 36}" class="cf-eg">{html.escape(eg)}</text>')
        if i < 2:
            b.append(f'<line x1="0" y1="{y + 50}" x2="700" y2="{y + 50}" class="d-rule"/>')
    b.append('</g>')
    return figure(
        _svg(700, 192,
             "The three confidence buckets",
             "Confirmed: the manifest names the target outright. Likely: parsed from config "
             "and matched to a catalog rule. Possible: something is there but nothing names it.",
             "".join(b)),
        min_width=600)


